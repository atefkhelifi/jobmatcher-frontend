const dictionaries: Record<Lang, Record<Key, string>> = { en, fr };

@Injectable({ providedIn: 'root' })
export class I18n {
  private readonly _lang = signal<Lang>(this.initial());
  readonly lang = this._lang.asReadonly();

  use(lang: Lang) {
    this._lang.set(lang);
    document.documentElement.lang = lang;
    try {
      localStorage.setItem('jm.lang', lang);
    } catch {
      /* storage can be unavailable; the choice then lasts for this visit only */
    }
  }

  /** Reads the language signal, so templates calling it re-render when the language changes. */
  t(key: Key, params?: Record<string, string | number>): string {
    let s = dictionaries[this._lang()][key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  }

  private initial(): Lang {
    try {
      const saved = localStorage.getItem('jm.lang');
      if (saved === 'en' || saved === 'fr') {
        return saved;
      }
    } catch {
      /* ignore */
    }
    return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
  }
}

export const DICTIONARIES = dictionaries;
